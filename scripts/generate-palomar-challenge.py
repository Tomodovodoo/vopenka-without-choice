"""Copy the independently defined vocabulary into Palomar's standalone statement.

Palomar forbids project imports from Challenge. The Solution imports Vocabulary
normally. Comparator checks that both environments contain the same definitions.
"""
import argparse
from pathlib import Path
import re

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
vocabulary = (root / 'PalomarBridge/Vocabulary.lean').read_text(encoding='utf-8').rstrip()
def vocabulary_body(text):
    text = re.sub(r'^module\s*\n', '', text, flags=re.M)
    text = re.sub(r'^(?:public )?import .+\n', '', text, flags=re.M)
    text = text.replace('@[expose] public section', '')
    return text.strip()

vocabulary = ('module\n\npublic import Mathlib.Data.Fin.VecNotation\n\n'
              '@[expose] public section\n\n' + vocabulary_body(vocabulary))
statement = '''

namespace VopenkaWithoutChoice

/-- Theorem B. There is a set-sized model of ZFC plus the full parameterized
Vopěnka scheme if and only if there is such a model of ZF plus that scheme.
By first-order completeness this is the paper's equiconsistency assertion.
The domain may be externally ill-founded. No external countability assumption
is imposed. Every definition used here is given above or imported from mathlib.
-/
theorem palomar_equiconsistency :
    PalomarBridge.HasZFCVPModel ↔ PalomarBridge.HasZFVPModel := by
  sorry

end VopenkaWithoutChoice
'''
content = ('-- Generated by scripts/generate-palomar-challenge.py.\n'
           '-- Edit PalomarBridge/Vocabulary.lean and regenerate.\n' + vocabulary + '\n' + statement)
preservation = (root / 'PalomarPreservationBridge/Vocabulary.lean').read_text(encoding='utf-8')
preservation = preservation.removeprefix('import PalomarBridge.Vocabulary\n').strip()
preservation = vocabulary_body(preservation)
preservation_statement = '''

namespace VopenkaWithoutChoice

/-- Theorem A. The specified symmetric quotient exists and every presentation
of it satisfies ZF and full VP. The generic is supplied; there is no external
countability, transitivity or well-foundedness assumption on the ground. -/
theorem palomar_preservation {M : Type u} (mem : M → M → Prop) [Nonempty M]
    (hZF : PalomarBridge.IsZF mem) (hVP : PalomarBridge.Coding.Vopenka mem)
    (d : PalomarPreservationBridge.SymmetricData mem) :
    (∃ (W : Type u) (wmem : W → W → Prop),
      PalomarPreservationBridge.Presentation mem d W wmem) ∧
    ∀ (W : Type u) (wmem : W → W → Prop),
      PalomarPreservationBridge.Presentation mem d W wmem →
        PalomarPreservationBridge.IsZFVPModel wmem := by
  sorry

end VopenkaWithoutChoice
'''
preservation_content = ('-- Generated by scripts/generate-palomar-challenge.py.\n'
    '-- Edit the two bridge Vocabulary.lean files and regenerate.\n'
    + vocabulary + '\n\n' + preservation + '\n' + preservation_statement)
dc_vocabulary = (root / 'PalomarDCBridge/Vocabulary.lean').read_text(encoding='utf-8')
dc_vocabulary = dc_vocabulary.removeprefix('import PalomarBridge.Vocabulary\n').strip()
dc_vocabulary = vocabulary_body(dc_vocabulary)
dc_statement = '''

namespace VopenkaWithoutChoice

/-- The consistency consequence with DC and failure of choice, expressed as
model existence. The bridge proves equivalence to syntactic consistency. -/
theorem palomar_dependent_choice (h : PalomarBridge.HasZFVPModel) :
    PalomarDCBridge.HasZFVPDCNotChoiceModel := by
  sorry

end VopenkaWithoutChoice
'''
dc_content = ('-- Generated by scripts/generate-palomar-challenge.py.\n'
    + vocabulary + '\n\n' + dc_vocabulary + '\n' + dc_statement)
solovay_vocabulary = (root / 'PalomarSolovayBridge/Vocabulary.lean').read_text(encoding='utf-8')
solovay_vocabulary = solovay_vocabulary.removeprefix('import PalomarDCBridge.Vocabulary\n').strip()
solovay_vocabulary = vocabulary_body(solovay_vocabulary)
solovay_statement = '''

namespace VopenkaWithoutChoice

/-- The ordinary-real Solovay consistency consequence. The explicit target
includes all three regularity properties and the ultrafilter clause. -/
theorem palomar_solovay_reals (h : PalomarBridge.HasZFVPModel) :
    PalomarSolovayBridge.HasSolovayModel := by
  sorry

end VopenkaWithoutChoice
'''
solovay_content = ('-- Generated by scripts/generate-palomar-challenge.py.\n'
    + vocabulary + '\n\n' + dc_vocabulary + '\n\n' + solovay_vocabulary + '\n' + solovay_statement)
paper_content = ('-- Generated by scripts/generate-palomar-challenge.py.\n'
    + '\n\n'.join([vocabulary, preservation, dc_vocabulary, solovay_vocabulary])
    + '\n' + preservation_statement + statement + dc_statement + solovay_statement)
solution_files = ['PalomarPreservationSolution.lean', 'PalomarSolution.lean',
                  'PalomarDCSolution.lean', 'PalomarSolovaySolution.lean']
solution_imports, solution_bodies = [], []
for filename in solution_files:
    source = (root / filename).read_text(encoding='utf-8')
    matches = re.findall(r'^(?:public )?import .+$', source, re.M)
    if len(matches) != 1:
        raise SystemExit(f'Expected a leading proof import in {filename}.')
    solution_imports.append(matches[0])
    solution_bodies.append(vocabulary_body(source))
paper_solution = ('-- Generated from the four individual Solution files.\n'
    + 'module\n\n' + '\n'.join(solution_imports)
    + '\n\n@[expose] public section\n\n' + '\n\n'.join(solution_bodies) + '\n')
for filename, generated in [('PalomarChallenge.lean', content),
                            ('PalomarPreservationChallenge.lean', preservation_content),
                            ('PalomarDCChallenge.lean', dc_content),
                            ('PalomarSolovayChallenge.lean', solovay_content),
                            ('PalomarPaperChallenge.lean', paper_content),
                            ('PalomarPaperSolution.lean', paper_solution)]:
    output = root / filename
    if args.check:
        if not output.exists() or output.read_text(encoding='utf-8') != generated:
            raise SystemExit(f'{filename} differs from its vocabulary and statement recipe.')
        print(f'{filename} matches the shared vocabulary.')
    else:
        output.write_text(generated, encoding='utf-8', newline='\n')
        print(f'Wrote {filename}: {len(generated.splitlines())} lines, {len(generated.encode())} bytes')
